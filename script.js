const canvas = document.querySelector("#atmosphere");
const context = canvas.getContext("2d");
if (!reduceMotion && context) {
  let width = 0;
  let height = 0;
  let frame = 0;
  const pixelRatio = Math.min(window.devicePixelRatio || 1, 1.25);
  const embers = Array.from({ length: 28 }, () => ({
    x: Math.random(), y: Math.random(), size: Math.random() * 1.6 + 0.45,
    speed: Math.random() * 0.00038 + 0.00012, drift: (Math.random() - 0.5) * 0.00018,
    alpha: Math.random() * 0.4 + 0.12,
  }));
  const resizeCanvas = () => {
    width = window.innerWidth;
    height = window.innerHeight;
    canvas.width = Math.round(width * pixelRatio);
    canvas.height = Math.round(height * pixelRatio);
    context.setTransform(pixelRatio, 0, 0, pixelRatio, 0, 0);
  };
  const drawEmbers = () => {
    context.clearRect(0, 0, width, height);
    embers.forEach((ember) => {
      ember.y -= ember.speed;
      ember.x += ember.drift;
      if (ember.y < -0.02) { ember.y = 1.02; ember.x = Math.random(); }
      if (ember.x < -0.02 || ember.x > 1.02) ember.drift *= -1;
      context.beginPath();
      context.fillStyle = `rgba(255, 108, 27, ${ember.alpha})`;
      context.arc(ember.x * width, ember.y * height, ember.size, 0, Math.PI * 2);
      context.fill();
    });
    frame = window.requestAnimationFrame(drawEmbers);
  };
  resizeCanvas();
  drawEmbers();
  window.addEventListener("resize", resizeCanvas, { passive: true });
  window.addEventListener("pagehide", () => window.cancelAnimationFrame(frame), { once: true });
}

